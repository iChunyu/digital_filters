/**
 * @file    notch_filter.c
 * @brief   二阶陷波滤波器的设计。
 */

#include "notch_filter.h"
#include "filter_utils.h"
#include <math.h>

/* ================================================================== */
/*  f32 设计参数范围闸                                                  */
/* ================================================================== */
/*
 * 定位先说清楚：**本库不负责修复、补偿或消除 f32 系数量化误差**——那是
 * 数值类型的固有代价，属于调用方的选择范围。这道闸只做一件事：拒绝
 * 已知会**静默失真**的参数范围（谷底变浅、中心偏移，而 valid 仍为 1）。
 * 性质与 biquad_filter_init 里那条极点半径裕量闸（1 - r < 5e-5）相同：
 * 不试图修好什么，只是不在明知会失真时还点头。
 *
 * 之所以需要它：本库其余各族的失真都至少能被 check_cascade_gains 这类
 * 解析校验捕捉，而陷波器的失真**无法在 f32 下事后验证**——在被拒的参数上
 * 求 |H(jω0)| 本身就是那个病态运算，算出来的是舍入噪声；DC/Nyquist 增益
 * 则无论设计多坏都精确是 1/1（分子分母在 z = ±1 处逐项相消，结构保证）。
 * 所以这道闸只能建在参数上、必须在设计之前判。
 *
 * 失效区长这样：归一化频率 f0/fs 太低（或陷波太深）时，f32 系数承载不住
 * 陷波深度。**换结构解决不了**——直接 DF-II、旁通形式（H = 1 - c(1-z^-2)/D）、
 * 耦合型（coupled form）实测在同一个 f0/fs 处一起失效（耦合型把 DF-II 的
 * 1.4e6 状态压到 3.7e3，包络分毫未动）。病根是系数量化，不是状态溢出。
 *
 * 推导
 * ----
 * 预畸后 a0 = ω0² + 2ξω0K + K²（K = 2fs），归一化分母
 * a1 = (2ω0² - 2K²)/a0，a2 = (ω0² - 2ξω0K + K²)/a0。
 * 分子与分母的 s⁰、s² 系数相同（都是 ω0² 和 1），只有 s¹ 系数不同
 * （2ξgω0 对 2ξω0），因此经 biquad_c2d_bilinear 之后
 *
 *     b1 == a1        （逐位相等，不是近似）
 *
 * 于是整个传递函数可以写成
 *
 *     H(z) = 1 + c·(z^-2 - 1) / (1 + a1 z^-1 + a2 z^-2),
 *     c = 2ξω0K(1-g)/a0
 *
 * **陷波深度只活在这个 c 里**，而 c ~ 1e-4 量级（f0=20Hz/48kHz, ξ=0.05,
 * g=0.1 时 c = 1.178e-4）。b0、b2、a2 各自带 ±1 ulp（≈1.2e-7）绝对误差，
 * 对 c 的相对扰动就是 1e-7/1.178e-4 ≈ 0.1%。
 *
 * 换结构解决不了。实测旁通形式（H = 1 + c(z^-2-1)/D，深度改由 c 单点承载）
 * 与耦合型（coupled form）在**同一个** f0/fs 处一起失效。耦合型把 DF-II 的
 * 1.4e6 状态压到 3.7e3，包络分毫未动——病根是系数量化，不是状态溢出。
 * （附带结论：耦合型的角度若用 acos 从 a1 反解会更加病态，θ 误差 0.9%，
 * 必须直接用模拟原型算；即使用对了，它的可用下限也只比 DF-II 低约 25 倍，
 * 见 CLAUDE.md。）
 *
 * 这点扰动本不致命，但陷波频率处的分母极小：
 *
 *     |D(e^{jθ0})| ≈ 8π²·ξ·(f0/fs)²
 *
 * （f0=20Hz/48kHz 时算出 6.96e-7，数值求值实测 6.955e-7，吻合）。相对
 * 深度误差 ≈ δ/(g·|D|) ∝ 1/[ξ·g·(f0/fs)²]，于是分母把它放大了 ~1e7 倍，
 * 正好吃掉 f32 的全部 7.2 位十进制。
 *
 * 时域上等价的说法：DF-II 的状态放大 1/(1+a1+a2) ≈ (fs/πf0)² 倍
 * （f0=20Hz/48kHz 时 1.5e5），输出 b0·w0 + b1·w1 + b2·w2 要把 ~1.45e6
 * 量级的三项相消到 g = 0.1。而系数误差 δb·|w| = 1.2e-7 × 1.45e6 ≈ 0.17，
 * 与真实输出同量级。窄带低通没有这个问题——它分子三项同号相加，输出与
 * 状态同量级，不存在相消；**陷波是全库唯一在 DF-II 下病态的滤波器**。
 *
 * 标定（下面这段只服务于闸门阈值的选取，与"库是否负责量化误差"无关）
 * ------------------------------------------------------------------
 * 令 Q = ξ·g·(ω0/K)²。实测 f32 深度 / 目标深度的**邻域最坏值**
 * （每个标定点扫 400 个 ±1% 内的邻近 f0，fs = 48 kHz）：
 *
 *     Q = 2e-9  最坏 12.1x       Q = 5e-8  最坏 1.17x
 *     Q = 5e-9  最坏  3.50x      Q = 1e-7  最坏 1.04x
 *     Q = 1e-8  最坏  2.79x      Q = 2e-7  最坏 1.011x
 *     Q = 2e-8  最坏  1.95x      Q = 1e-6  最坏 1.0006x
 *
 * 换不同 (ξ, g) 组合凑到同一 Q 时最坏值有约 ±50% 的散布（Q = 5e-8 时
 * 实测 1.12~1.19），Q 越大散布越小，故阈值取 Q ≥ 5e-8：跨全部实测
 * (ξ, g) 组合，闸内深度误差 < 20%。
 *
 * **标定必须在邻域上取最坏，不能采孤立点。** 失效在 0.002 Hz 尺度上
 * 剧烈震荡——f0 = 19.95~20.05 Hz（fs = 48kHz, ξ = 0.05, g = 0.1）区间内
 * 比值在 1.04 和 3.04 之间随机跳，相邻 0.002 Hz 步长给出 1.28 → 2.73 →
 * 1.40。那些"好"的值只是舍入运气好，不是真可用。按孤立点标定会得出
 * 一个乐观 25~50 倍的阈值。
 *
 * 判据是纯乘除（ω0/K = tan(πf0/fs)，而 ω0 为预畸本来就要算），不引入
 * 新的 libm 调用。
 */
#define NOTCH_GATE 5.0e-8f

/*
 * g 的上限。g 趋近 1 时陷波浅于 0.001 dB，等同不陷波（g = 1 时分子分母
 * 逐项相等，H ≡ 1），按直通部署更划算：否则要烧一个高 Q 极点结构，把状态
 * 推到 1.5e5 量级，再靠 b0·w0 + b1·w1 + b2·w2 精确相消回单位增益——
 * 那个相消正是本文档开头描述的病态运算，白冒风险却什么都没滤掉。
 */
#define NOTCH_G_MAX 0.9999f

void notch_init(notch_filter_t *f, float f0, float xi, float g, float fs)
{
    f->f0 = f0;
    f->xi = xi;
    f->g = g;
    f->fs = fs;
    f->valid = 0;
    f->num_sections = 0; /* valid=0 时绝不能留下这个垃圾值 */

    /*
     * 参数闸。写成 !(x > 0) 而不是 x <= 0：NaN 与任何数比较恒假，
     * 后者会放 NaN 过去，前者拦得住。butter_filter.c 用的
     * `fc <= 0.0f || fc >= fs * 0.5f` 正是漏掉 NaN 的写法——那里下游
     * design_filter 的有限性闸兜住了，本文件没有那层兜底，必须在入口拦。
     */
    if (!(fs > 0.0f)) return;
    if (!(f0 > 0.0f) || !(f0 < fs * 0.5f)) return;
    if (!(xi > 0.0f)) return;
    if (!(g > 0.0f)) return;    /* !(x > 0) 同时拦下 NaN 与 g <= 0 */
    if (g >= NOTCH_G_MAX) return; /* 浅到等同不陷波 → 直通 */

    /*
     * 预畸：ω0 必须精确落到数字频率 f0 上，否则陷波中心偏移。
     * prewarp 对越界输入返回 NaN（双线性映射在 Nyquist 以外无定义），
     * 上面的闸已把越界挡掉，这里只做有限性兜底。
     */
    float w0 = 2.0f * (float)M_PI * prewarp(f0, fs);
    float K = 2.0f * fs;
    if (!isfinite(w0)) return;

    /* f32 设计参数范围闸——见文件头。低于此范围时谷底会静默变浅、中心偏移，
       而下游所有校验都察觉不到。 */
    float r = w0 / K;
    if (!(xi * g * r * r >= NOTCH_GATE)) return;

    /*
     * 直写 biquad：二阶级没有配对问题，不必走 design_filter/zpk2sos。
     * num_s/den_s 按升幂存放（[s^0, s^1, s^2]），与
     * biquad_c2d_bilinear 的约定一致。
     */
    const float num_s[3] = { w0 * w0, 2.0f * xi * g * w0, 1.0f };
    const float den_s[3] = { w0 * w0, 2.0f * xi * w0, 1.0f };

    float num_z[3];
    float den_z[3];
    biquad_c2d_bilinear(num_z, den_z, num_s, den_s, fs);

    /* 系数有限性、Jury 稳定性、极点半径裕量全在这一步，失败即直通。 */
    if (!biquad_filter_init(&f->sections[0], num_z, den_z)) return;

    /*
     * 级联增益闸：DC 与 Nyquist 恒为 1，且是结构保证而非巧合——b1 == a1
     * 且 b0-1 = -(b2-a2)，在 z = ±1 处分子分母逐项相消。因此这一步几乎
     * 不可能失败，保留它是为了与另两族同构，并兜住任何粗粒度算错
     * （num_s/den_s 传反、c2d 参数错等）。
     */
    if (!check_cascade_gains(f->sections, 1, 1.0f, 1.0f)) return;

    f->num_sections = 1;
    f->valid = 1;
}
