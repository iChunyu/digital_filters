/**
 * @file    peak_filter.c
 * @brief   二阶峰值滤波器（Peak / boost）的设计。
 */

#include "peak_filter.h"
#include "filter_utils.h"
#include <math.h>

/* ================================================================== */
/*  为什么是 H1（分母带 g）而不是 H2（分子带 g）                        */
/* ================================================================== */
/*
 * 两种候选原型在 f0 处的增益都精确等于 g，差别只在带宽：
 *
 *     H1 = (s² + 2ξω₀s + ω₀²) / (s² + 2ξω₀/g·s + ω₀²)   ← 本族采用
 *     H2 = (s² + 2ξgω₀s + ω₀²) / (s² + 2ξω₀s + ω₀²)     ← notch 的形式
 *
 * H1 是唯一与已有陷波族语义对称的选择，因为它满足
 *
 *     H1(ξ,g) ≡ 1 / H2(ξ,1/g)          （逐点恒等，数值验证偏差 ~2e-15）
 *
 * 即 g = 10 的 boost 就是已验证的 g = 0.1 陷波的镜像：同一个 ξ 下，
 * boost 与 cut 的相对带宽一致（√g 电平处全宽都是 2ξ·f₀/√g·... 见下）。
 * 用 H2 做 boost 会得到一个宽 g 倍的峰——g = 10、ξ = 0.05、f₀ = 20 Hz 时
 * √g 电平全宽 H1 是 0.632 Hz、H2 是 6.32 Hz，H2 在 f₀/2 处已经 +1.58 dB
 * （H1 只有 +0.02 dB），boost/cut 严重不对称。
 *
 * 还有第三种原型（RBJ 对称型 HR：把 √g 平分给分子分母，Q = 1/(2ξ) 与增益
 * 无关）。若将来需要"Q 不随增益变"的经典 peaking EQ 语义，那要换 HR，
 * 而不是 H1/H2 里的任何一个。
 *
 * 数值上的代价：H1 的窄峰正是深陷波的倒数，所以它的 f32 病态与
 * notch_filter.c 描述的那个**同一个**——下面的闸门就是为此存在。
 */

/* ================================================================== */
/*  f32 设计参数范围闸                                                  */
/* ================================================================== */
/*
 * 定位与 notch_filter.c 完全一致：本库不负责修复、补偿或消除 f32 系数
 * 量化误差；这道闸只拒绝已知会**静默失真**的参数范围（峰高变矮、中心
 * 偏移，而 valid 仍为 1）。性质与 biquad_filter_init 的极点半径裕量闸
 * 相同：不试图修好什么，只是不在明知会失真时还点头。
 *
 * 判据用 d = 1/g，不是 g
 * ----------------------
 * 由 H1(ξ,g) = 1/H2(ξ,1/g) 可知，"g 的 boost 有多难做"与"d = 1/g 的
 * 陷波有多难做"是**同一个问题**——不是相似，是同一个。notch_filter.c
 * 里那段推导（深度只活在 c ~ 1e-4 里、b0/b2/a2 各带 ±1 ulp、谷底处
 * |D(e^{jθ0})| ≈ 8π²ξ(f0/fs)² 把扰动放大 ~1e7 倍）在这里逐字适用，
 * 只需把深度记作 d。
 *
 * 因此闸门必须写成 Q = ξ·d·(ω₀/K)² ≥ 5e-8。若图省事直接用 g，闸门会
 * 随增益被放大约 g² 倍：f0 = 20 Hz、fs = 48 kHz、ξ = 0.05、g = 10
 * （d = 0.1）时
 *
 *     用 d：Q = 8.567e-9  < 5e-8  → 拒绝   （正确）
 *     用 g：Q = 8.567e-7  ≥ 5e-8  → 放行   （错误，g² = 100 倍）
 *
 * 而它的镜像陷波（g = 0.1）在同一点是被拒的——同一个病态，闸门却放行，
 * 这正是"参数闸必须在设计之前判"要避免的事。
 *
 * 极点半径闸通常比数值闸更紧
 * --------------------------
 * 峰值的极点阻尼是 ξ/g，故 1 − r ≈ 2ξ·tan(πf0/fs)/g。要求
 * 1 − r ≥ 5e-5（biquad_filter_init 的裕量闸）即
 *
 *     g ≤ 4e4 · ξ · tan(π f0/fs)
 *
 * ξ = 0.05 时：f0/fs = 0.05 → g ≤ 317（50 dB）；f0/fs = 2e-3 → g ≤ 12.6
 * （22 dB）。而数值闸要求 f0/fs ≥ 1.007e-3（与陷波器同值，因为用的是
 * 同一个 d）。两者取交集，且**半径闸一般先触发**——所以 boost 的可用
 * 上限主要由"极点离单位圆够不够远"决定，随 f0/fs 线性增长。
 *
 * 标定（下面这段只服务于闸门阈值的选取）
 * --------------------------------------
 * 用 **f32 系数 + f32 状态递推的 DF-II 时域仿真**（与
 * biquad_filter_update 同结构），每个 fs 扫 f0 的 ±1% 邻域取最坏
 * （孤立点会因舍入运气给出乐观值，见 notch_filter.c 的同一告诫）。
 * f0 = 20 Hz、ξ = 0.05、g = 10：
 *
 *     fs = 1 kHz    比值误差 < 3e-5      实测 10 ~ 10
 *     fs = 8 kHz    2.8e-4              实测 9.997 ~ 10
 *     fs = 48 kHz   0.289               实测 7.113 ~ 11.06（半径闸拒绝）
 *
 * 镜像核对：同点 g = 0.1 的陷波深度实测 0.126 ~ 0.166（理想 0.1，
 * 最坏 66%），与上面 29% 是互为倒数的同一个病态。
 *
 * **不要用「f32 系数 + f64 解析求值」标定**。那个口径在 f0 = 20 Hz、
 * fs = 48 kHz 上给陷波 0.4%、boost 0.4% 的误差，比真实值低估两个
 * 数量级——它忽略了 f32 **状态**舍入，而这里的状态 |w| ≈ 1/|D(e^{jθ0})|
 * 会到 1e7 量级，其 ulp（≈1.0）本身就和输出同量级。系数误差只是
 * 病态的一半，另一半在状态里。
 */
#define PEAK_GATE 5.0e-8f

/*
 * 等效陷波深度的上限。d ≥ 0.9999 ⇔ g ≤ 1.0001 时峰值浅于 0.001 dB，
 * 等同不 boost——与 notch_filter.c 的 NOTCH_G_MAX（凹陷浅于 0.001 dB）
 * 互为镜像，同样按直通部署：一边是什么都不做，一边是烧一个高 Q 极点
 * 结构再把巨大的状态精确相消回单位增益。
 */
#define PEAK_D_MAX 0.9999f

void peak_init(peak_filter_t *f, float f0, float xi, float g, float fs)
{
    f->f0 = f0;
    f->xi = xi;
    f->g = g;
    f->fs = fs;
    f->valid = 0;
    f->num_sections = 0; /* valid=0 时绝不能留下这个垃圾值 */

    /*
     * 参数闸。写成 !(x > 0) 而不是 x <= 0：NaN 与任何数比较恒假，
     * 后者会放 NaN 过去，前者拦得住。
     */
    if (!(fs > 0.0f)) return;
    if (!(f0 > 0.0f) || !(f0 < fs * 0.5f)) return;
    if (!(xi > 0.0f)) return;
    if (!(g > 1.0f)) return; /* 同时拦下 NaN 与 g <= 1 */

    /* 等效陷波深度：本族全部数值分析的统一参数。 */
    float d = 1.0f / g;

    /* g = +Inf 时 d = 0，不在此拦（0 < 0.9999 成立），由下面的数值闸
       以 Q = 0 拒掉。 */
    if (!(d < PEAK_D_MAX)) return; /* g <= 1.0001，浅到等同不 boost */

    /*
     * 预畸：ω0 必须精确落到数字频率 f0 上，否则峰中心偏移。
     * prewarp 对越界输入返回 NaN（双线性映射在 Nyquist 以外无定义），
     * 上面的闸已把越界挡掉，这里只做有限性兜底。
     */
    float w0 = 2.0f * (float)M_PI * prewarp(f0, fs);
    float K = 2.0f * fs;
    if (!isfinite(w0)) return;

    /* f32 设计参数范围闸——见文件头。判据用 d 而不是 g。 */
    float r = w0 / K;
    if (!(xi * d * r * r >= PEAK_GATE)) return;

    /*
     * 直写 biquad：二阶级没有配对问题，不必走 design_filter/zpk2sos。
     * num_s/den_s 按升幂存放（[s^0, s^1, s^2]），与
     * biquad_c2d_bilinear 的约定一致。
     *
     * 分母写成 2·xi·d·w0（而不是 2·xi·w0/g）是为了与 notch_init 的
     * 分子表达式 2·xi·g·w0 逐位同形：这样 peak_init(f0,xi,g,fs) 与
     * notch_init(f0,xi,1/g,fs) 的 s 域系数向量互为精确交换，测试里
     * 可以直接校验这条对偶不变量。
     */
    const float num_s[3] = { w0 * w0, 2.0f * xi * w0, 1.0f };
    const float den_s[3] = { w0 * w0, 2.0f * xi * d * w0, 1.0f };

    float num_z[3];
    float den_z[3];
    biquad_c2d_bilinear(num_z, den_z, num_s, den_s, fs);

    /* 系数有限性、Jury 稳定性、极点半径裕量全在这一步，失败即直通。
       对本族而言这是**最常触发**的一道闸（极点阻尼 ξ/g，g 越大越靠近
       单位圆）。 */
    if (!biquad_filter_init(&f->sections[0], num_z, den_z)) return;

    /*
     * 级联增益闸：DC 与 Nyquist 恒为 1，且是结构保证而非巧合——
     * 与陷波器同理，num_s 与 den_s 的 s⁰、s² 系数相同，双线性后
     * b1 == a1 且 b0-1 = -(b2-a2)，在 z = ±1 处分子分母逐项相消。
     * 保留这一步是为了与另两族同构，并兜住任何粗粒度算错
     * （num_s/den_s 传反、c2d 参数错等）。
     */
    if (!check_cascade_gains(f->sections, 1, 1.0f, 1.0f)) return;

    f->num_sections = 1;
    f->valid = 1;
}
